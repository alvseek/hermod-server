-- Hermod's project store, PostgreSQL shape — the twin of `migrations/0001_init.sql`.
--
--   project_context   a project's context entries: shared or private, one live row per theme.
--   orientation_map   one map per project, stored whole.
--
-- Dates are TEXT (ISO-8601) and tags are a JSON array in TEXT, matching the entity mapping and
-- the SQLite backend exactly, so a value means the same thing in either engine and the contract
-- test runs unchanged against both. That is Munnin's choice for its own store, made for the same
-- reason. `id` is an identity column rather than SQLite's rowid alias: the entity's `id` never
-- leaves the store, so nothing depends on how the engine allocates it.
--
-- The unique index is partial on `deleted_date IS NULL` for the same reason as SQLite's: a
-- tombstone is not a live entry, so deleting a theme and creating it again is a new row, exactly
-- as removing and recreating a file is on the markdown backend.
--
-- No foreign keys and no FTS: the store is per-project and small, and every read is a filtered
-- list, so the browse index below is the whole access pattern.

CREATE TABLE IF NOT EXISTS project_context (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project       TEXT NOT NULL,
  scope         TEXT NOT NULL CHECK (scope IN ('shared', 'private')),
  theme         TEXT NOT NULL,
  description   TEXT,
  tags          TEXT,                   -- JSON array (stored as text)
  created_date  TEXT NOT NULL,
  modified_date TEXT NOT NULL,
  deleted_date  TEXT,                   -- non-NULL = tombstone, excluded from all reads
  full_content  TEXT                    -- the whole entry document; last column
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_project_context_identity
  ON project_context (project, scope, theme)
  WHERE deleted_date IS NULL;

CREATE INDEX IF NOT EXISTS idx_project_context_browse
  ON project_context (project, scope, created_date);

CREATE TABLE IF NOT EXISTS orientation_map (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project       TEXT NOT NULL UNIQUE,
  description   TEXT,
  created_date  TEXT NOT NULL,
  modified_date TEXT NOT NULL,
  full_content  TEXT
);

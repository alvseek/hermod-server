"""The record schema Hermod reads, for tests only.

Hermod does **not** own these tables. Munnin's migration runner creates them (decisions 6 and 7),
so their real shape lives in `agent-memory-server`, and this is a deliberate, minimal copy: the
two record tables plus the two parent tables their foreign keys point at, carrying the columns
this server reads or writes and nothing else. Munnin's `search_tsv`, its GIN indexes and its CHECK
constraints are absent on purpose, because nothing here touches them.

The copy is the one place the boundary costs something, so it is pinned rather than trusted: the
contract test runs against exactly this schema, so a column the code needs and this file lacks
fails on every op instead of being discovered in a deployment.

**No unique index on the natural identity, deliberately.** Uniqueness in this store is the `uuid`
alone, so `(user_id, project, title)` is a name rather than a key: two rows may carry one theme,
and the store checks nothing when it writes one. The absence is asserted here so a later change
that adds such an index has to change this file too.
"""

from __future__ import annotations

import psycopg

_DDL = """
CREATE TABLE account (
  user_id      TEXT PRIMARY KEY,
  display_name TEXT,
  email        TEXT,
  created_date TEXT NOT NULL
);
CREATE TABLE user_identity (
  iss         TEXT NOT NULL,
  sub         TEXT NOT NULL,
  user_id     TEXT NOT NULL,
  linked_date TEXT NOT NULL,
  PRIMARY KEY (iss, sub),
  FOREIGN KEY (user_id) REFERENCES account(user_id)
);
CREATE TABLE agent (
  user_id      TEXT NOT NULL REFERENCES account(user_id),
  agent_id     TEXT NOT NULL,
  name         TEXT,
  role         TEXT,
  uuid         TEXT,
  created_date TEXT NOT NULL,
  PRIMARY KEY (user_id, agent_id)
);
CREATE TABLE shared_record (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid          TEXT NOT NULL UNIQUE,
  user_id       TEXT NOT NULL,
  record_type   TEXT NOT NULL,
  project       TEXT,
  title         TEXT,
  tags          TEXT,
  created_date  TEXT NOT NULL,
  modified_date TEXT NOT NULL,
  archived_date TEXT,
  deleted_date  TEXT,
  full_content  TEXT,
  content_summary TEXT
);
CREATE TABLE memory_record (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid          TEXT NOT NULL UNIQUE,
  user_id       TEXT NOT NULL,
  agent_id      TEXT NOT NULL,
  record_type   TEXT NOT NULL,
  project       TEXT,
  title         TEXT,
  tags          TEXT,
  created_date  TEXT NOT NULL,
  modified_date TEXT NOT NULL,
  archived_date TEXT,
  deleted_date  TEXT,
  full_content  TEXT,
  content_summary TEXT,
  FOREIGN KEY (user_id, agent_id) REFERENCES agent (user_id, agent_id)
);
"""


def make_store(
    url: str,
    *,
    user_id: str,
    agents: tuple[str, ...],
    identity: tuple[str, str] | None = None,
) -> None:
    """A fresh store: the record schema, one account, the named agents, and an optional login.

    ``identity`` links one ``(iss, sub)`` pair to ``user_id``, which is what a caller without a
    token needs in order to name a tenant: the importer resolves that pair rather than being told
    an id, so a test of it has to seed the mapping a real login would have written.
    """
    with psycopg.connect(url) as conn:
        with conn.cursor() as cur:
            cur.execute("DROP SCHEMA public CASCADE; CREATE SCHEMA public;")
            cur.execute(_DDL)
            cur.execute(
                "INSERT INTO account (user_id, created_date) VALUES (%s, '2026-01-01')",
                (user_id,),
            )
            for agent in agents:
                cur.execute(
                    "INSERT INTO agent (user_id, agent_id, created_date) "
                    "VALUES (%s, %s, '2026-01-01')",
                    (user_id, agent),
                )
            if identity is not None:
                cur.execute(
                    "INSERT INTO user_identity (iss, sub, user_id, linked_date) "
                    "VALUES (%s, %s, %s, '2026-01-01')",
                    (identity[0], identity[1], user_id),
                )
        conn.commit()
